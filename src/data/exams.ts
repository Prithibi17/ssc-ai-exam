export function getExamSubjectCodes(examId: string, tierIndex: number = 0): string[] {
  const exam = EXAMS_CATALOGUE.find((e) => e.id === examId);
  if (!exam || !exam.tiers[tierIndex]) return ['quant', 'reasoning', 'english', 'ga'];
  return exam.tiers[tierIndex].sections.map((s) => s.code);
}

export function getExamExcludedSubjects(examId: string, tierIndex: number = 0): { code: string; name: string }[] {
  const allowed = getExamSubjectCodes(examId, tierIndex);
  return SUBJECTS_CATALOGUE
    .filter((s) => !allowed.includes(s.code))
    .map((s) => ({ code: s.code, name: s.name }));
}


